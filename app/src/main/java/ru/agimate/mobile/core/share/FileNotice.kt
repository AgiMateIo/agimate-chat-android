package ru.agimate.mobile.core.share

import ru.agimate.mobile.core.ui.text.UiText

/**
 * Короткая строка о файле: «сохраняю…», «сохранено в галерею», «ссылка устарела».
 *
 * Общая для чата и списка файлов: действия над вложением одни и те же, и отвечать о них надо
 * одинаково. Отдельно от полоски ошибки отправки: та висит, пока человек её не перебьёт, а эта
 * рассказывает про уже законченное дело и гаснет сама.
 */
data class FileNotice(val text: UiText, val failed: Boolean = false)
